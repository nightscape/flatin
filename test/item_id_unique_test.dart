String _norm(String text) => normalizeDiacritics(text).toLowerCase();

String _lemma(YamlMap item, String lemmaPart) {
  final spelling = (item['parts'] as YamlMap)[lemmaPart];
  return spelling is YamlList ? '${spelling.first}' : '$spelling';
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('items whose lemmas normalize alike each carry an explicit id', () {
    for (final path in _dataFiles) {
      final doc = loadYaml(File(path).readAsStringSync()) as YamlMap;
      final lemmaPart = (doc['defaults'] as YamlMap)['lemma_part'] as String;
      final byNorm = <String, List<YamlMap>>{};
      for (final item in (doc['items'] as YamlList).cast<YamlMap>()) {
        byNorm.putIfAbsent(_norm(_lemma(item, lemmaPart)), () => []).add(item);
      }
      for (final entry in byNorm.entries) {
        final implicit = entry.value.where((i) => i['id'] == null).length;
        expect(
          implicit,
          lessThanOrEqualTo(1),
          reason: '$path: "${entry.key}" is the implicit id of $implicit items',
        );
        if (entry.value.length > 1) {
          expect(
            implicit,
            lessThan(entry.value.length),
            reason: '$path: "${entry.key}" has no explicit id among its items',
          );
        }
      }
    }
  });

  test('all item ids are unique', () async {
    final ids = (await loadAllPracticeItems()).map((i) => i.id).toList();
    expect(ids.toSet().length, ids.length);
  });

  test('every pre-existing item id is unchanged', () async {
    final ids = (await loadAllPracticeItems()).map((i) => i.id).toSet();
    expect(ids, containsAll(_existingIds));
  });
}
