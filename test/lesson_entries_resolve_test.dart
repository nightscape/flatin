void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test(
    'every entry of every lesson list resolves to a practice item',
    () async {
      final lessons = await loadLessonData(bookAssets);
      final lemmas = {for (final i in await loadAllPracticeItems()) i.lemma};

      final unresolved = {
        for (final MapEntry(key: lesson, value: words)
            in lessons.lessonWords.entries)
          for (final word in words)
            if (!lemmas.contains(word)) 'Lektion $lesson: $word',
      };

      expect(
        unresolved.where((e) => !_unresolved.containsKey(e)),
        isEmpty,
        reason: 'lesson entries without an item',
      );
      expect(
        _unresolved.keys.where((e) => !unresolved.contains(e)),
        isEmpty,
        reason: 'allow-listed entries that resolve now',
      );
    },
  );
}
