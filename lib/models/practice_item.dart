import 'derivation.dart';
import 'form_label.dart';

export 'form_label.dart';

/// Generic practice item loaded directly from YAML
class PracticeItem {
  /// `<dataFileId>:<lemma without quantity marks, lower case>`.
  final String id;

  /// The word as a dictionary names it.
  final String lemma;

  final String type;
  final String translation;

  /// [translation] in the course language: the book's meaning, which decides
  /// whether two vocab items overlap in every UI language.
  final String bookTranslation;

  /// The spellings the item gives, in file order, each with the text that
  /// names it to the learner; an empty label is not shown.
  final List<(String partLabel, String value)> principalParts;

  final List<FormKey> formOrder;

  /// The shown spelling of every key of [formOrder].
  final List<String> forms;

  /// Every accepted spelling per key; `acceptedForms[i].first == forms[i]`.
  final List<List<String>> acceptedForms;

  final List<FormLabel> formLabels;
  final List<String>? possibleTypes;
  final String dataFileId; // 'nouns', 'verbs' or 'vocab'

  /// A word or phrase practised by its meaning only: one cell, the word
  /// itself, and no grammar the course teaches.
  bool get isVocab => dataFileId == 'vocab';

  /// Forms as generated by pattern inference only (before explicit overrides).
  /// For regular words this equals [forms]. For irregular words these are the
  /// "regular" variants that the pattern would produce.
  final List<String> inferredForms;

  /// How every form of this item follows from its principal parts.
  final Derivation derivation;

  PracticeItem({
    required this.id,
    required this.lemma,
    required this.type,
    required this.translation,
    required this.bookTranslation,
    required this.principalParts,
    required this.forms,
    required this.acceptedForms,
    required this.formLabels,
    this.possibleTypes,
    required this.dataFileId,
    required this.formOrder,
    required this.derivation,
    List<String>? inferredForms,
  }) : inferredForms = inferredForms ?? forms,
       assert(principalParts.isNotEmpty),
       assert(forms.length == formOrder.length),
       assert(formLabels.length == formOrder.length),
       assert(acceptedForms.length == formOrder.length),
       assert(() {
         for (int i = 0; i < forms.length; i++) {
           if (acceptedForms[i].first != forms[i]) return false;
         }
         return true;
       }(), 'the first accepted spelling is the shown one');

  /// Get all forms that need to be practiced
  List<String> get allForms => forms;

  /// Whether [answer] is one of the accepted spellings of row [index].
  bool accepts(int index, String answer) =>
      acceptedForms[index].any((form) => norm(form) == norm(answer));

  /// Filter forms and labels based on enabled form keys
  ({
    List<String> forms,
    List<FormLabel> labels,
    List<String> inferredForms,
    List<String> keys,
  })
  filterForms(Set<String> enabledFormKeys) {
    final filteredForms = <String>[];
    final filteredLabels = <FormLabel>[];
    final filteredInferred = <String>[];
    final filteredKeys = <String>[];

    for (int i = 0; i < formOrder.length; i++) {
      final formKey = formOrder[i];
      if (enabledFormKeys.contains(formKey)) {
        filteredForms.add(forms[i]);
        filteredLabels.add(formLabels[i]);
        filteredInferred.add(inferredForms[i]);
        filteredKeys.add(formKey);
      }
    }

    return (
      forms: filteredForms,
      labels: filteredLabels,
      inferredForms: filteredInferred,
      keys: filteredKeys,
    );
  }
}
